"""
AFTER: secure credential storage.


- A unique random 16-byte salt per password (generated by the library and
  stored inside the encoded hash string).
- A dummy hash check for unknown usernames, so response time does not
  reveal which usernames exist.
- Automatic rehash when parameters are later increased.
- Optional password policy enforcement at registration.


"""
import json

import bcrypt
from argon2 import PasswordHasher
from argon2.exceptions import InvalidHashError, VerificationError, VerifyMismatchError

from password_policy import check_password

ARGON2 = PasswordHasher(time_cost=2, memory_cost=19456, parallelism=1, hash_len=32, salt_len=16)
BCRYPT_COST = 12


class WeakPasswordError(ValueError):
    pass


class Argon2Store:
    def __init__(self, enforce_policy: bool = True):
        self.db = {}
        self.enforce_policy = enforce_policy
        self._dummy = ARGON2.hash("dummy-password-for-timing")

    def register(self, username: str, password: str) -> None:
        if self.enforce_policy:
            result = check_password(password, username=username)
            if not result.ok:
                raise WeakPasswordError("; ".join(result.errors))
        self.db[username] = ARGON2.hash(password)

    def verify(self, username: str, password: str) -> bool:
        stored = self.db.get(username)
        if stored is None:
            # Do the same amount of work so timing does not leak valid usernames.
            try:
                ARGON2.verify(self._dummy, password)
            except VerificationError:
                pass
            return False
        try:
            ARGON2.verify(stored, password)
        except (VerifyMismatchError, VerificationError, InvalidHashError):
            return False
        if ARGON2.check_needs_rehash(stored):
            self.db[username] = ARGON2.hash(password)
        return True


class BcryptStore:
    def __init__(self):
        self.db = {}

    def register(self, username: str, password: str) -> None:
        # bcrypt only uses the first 72 bytes of input.
        self.db[username] = bcrypt.hashpw(password.encode()[:72], bcrypt.gensalt(BCRYPT_COST)).decode()

    def verify(self, username: str, password: str) -> bool:
        stored = self.db.get(username)
        if stored is None:
            return False
        return bcrypt.checkpw(password.encode()[:72], stored.encode())


def demo() -> None:
    users = [("alice", "password123"), ("bob", "password123"), ("carol", "Tr0ub4dor&3")]

    store = Argon2Store(enforce_policy=False)  # policy off so we can compare the same inputs as BEFORE
    for u, p in users:
        store.register(u, p)

    print("=== AFTER: Argon2id salted hashes ===")
    print(json.dumps(store.db, indent=2))
    same = store.db["alice"] == store.db["bob"]
    print(f"\nalice and bob share a password -> identical hashes? {same}")
    print("Format: $argon2id$v=19$m=<memory KiB>,t=<iterations>,p=<lanes>$<salt>$<hash>")

    print("\n=== Login checks ===")
    print("alice / password123 ->", store.verify("alice", "password123"))
    print("alice / wrongpass   ->", store.verify("alice", "wrongpass"))
    print("mallory (no account)->", store.verify("mallory", "anything"))

    print("\n=== With password policy enforced at registration ===")
    strict = Argon2Store(enforce_policy=True)
    for u, p in [("dave", "password123"), ("erin", "correct horse battery staple")]:
        try:
            strict.register(u, p)
            print(f"{u}: '{p}' ACCEPTED")
        except WeakPasswordError as e:
            print(f"{u}: '{p}' REJECTED -> {e}")


if __name__ == "__main__":
    demo()
